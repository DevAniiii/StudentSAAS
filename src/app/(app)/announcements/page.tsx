import { redirect } from "next/navigation";
import type { Metadata } from "next";
import { getShellContext } from "@/server/context";
import { getAnnouncements, getNotifications } from "@/server/comms";
import { cn } from "@/lib/cn";
import { PageHeader, Panel } from "@/components/ui/panel";
import { NoticeBoard } from "@/components/pages/notice-board";

export const metadata: Metadata = { title: "Announcements" };

/**
 * Announcements and notifications.
 *
 * Two different things that happen to live near each other, kept visually
 * distinct on purpose:
 *
 *  - **Announcements** are broadcast. Everyone who matches the audience sees
 *    them, they are authored by staff, and they have a publication and expiry
 *    date. They are the page's main content.
 *  - **Notifications** are addressed to one person. They are generated by the
 *    system when something happens — a deadline approaching, a grade posted, a
 *    balance going overdue — and they carry a link to the thing that caused them.
 *
 * Merging them into one undifferentiated feed is the common mistake, and it
 * destroys the distinction between "this applies to you because of your
 * programme" and "this happened to your record".
 */

export default async function AnnouncementsPage() {
  const context = await getShellContext();
  if (!context) redirect("/login");

  const [announcements, notifications] = await Promise.all([
    getAnnouncements(context.user.id, context.now),
    getNotifications(context.user.id, 25),
  ]);

  const unread = notifications.filter((notification) => notification.readAt === null);

  return (
    <>
      <PageHeader
        eyebrow={context.term ? context.term.code : undefined}
        title="Announcements"
        description="Notices from the institute, your department, and the instructors of your courses. Only notices that apply to you are shown."
        actions={
          unread.length > 0 ? (
            <form action="/api/v1/notifications/read" method="post">
              <button
                type="submit"
                className="rounded-md border border-rule-strong px-3 py-1.5 text-xs font-medium text-ink transition-colors duration-fast hover:bg-hover focus-visible:outline-2 focus-visible:outline-offset-2 focus-visible:outline-accent"
              >
                Mark all as read
              </button>
            </form>
          ) : undefined
        }
      />

      <div className="grid gap-5 lg:grid-cols-[minmax(0,1fr)_minmax(0,18rem)] lg:items-start">
        <NoticeBoard
          announcements={announcements}
          now={context.now}
          timezone={context.timezone}
        />

        <NotificationLog
          notifications={notifications}
          now={context.now}
          timezone={context.timezone}
        />
      </div>
    </>
  );
}

const KIND_LABEL: Record<string, string> = {
  ASSIGNMENT_DUE: "Deadline",
  GRADE_POSTED: "Result",
  ATTENDANCE_RISK: "Attendance",
  PAYMENT_DUE: "Payment",
  ANNOUNCEMENT: "Notice",
  MESSAGE: "Message",
  ENROLLMENT: "Enrolment",
  ENROLLMENT_APPROVED: "Enrolment",
  ENROLLMENT_REJECTED: "Enrolment",
};

/**
 * The personal log.
 *
 * A vertical timeline rather than a list, because these events have a natural
 * order and the order is the content. Each entry is a dot on a rule — the same
 * ruled-paper motif as the spine — with the event hanging off it.
 *
 * Unread entries carry a filled dot and heavier type. Read entries do not lose
 * their place in the timeline; they simply stop asking for attention, which is
 * what "read" should mean.
 */
function NotificationLog({
  notifications,
  now,
  timezone,
}: {
  notifications: {
    id: string;
    kind: string;
    title: string;
    body: string;
    href: string | null;
    readAt: Date | null;
    createdAt: Date;
  }[];
  now: Date;
  timezone: string;
}) {
  if (notifications.length === 0) {
    return null;
  }

  const unreadCount = notifications.filter((notification) => notification.readAt === null).length;

  return (
    <Panel as="section" aria-labelledby="notification-log" tone="sunken">
      <div className="border-b border-rule px-4 py-3">
        <h2 id="notification-log" className="text-sm font-semibold text-ink">
          Your notifications
        </h2>
        <p className="mt-0.5 font-mono text-2xs tabular-nums text-ink-subtle">
          {unreadCount} unread of {notifications.length}
        </p>
      </div>

      <ol className="px-4 py-3">
        {notifications.map((notification, index) => {
          const isUnread = notification.readAt === null;
          const last = index === notifications.length - 1;

          const body = (
            <>
              <span className="flex items-baseline gap-2">
                <span className="font-mono text-[0.6rem] uppercase tracking-[0.12em] text-ink-subtle">
                  {KIND_LABEL[notification.kind] ?? notification.kind.toLowerCase()}
                </span>
                <time
                  dateTime={notification.createdAt.toISOString()}
                  className="ml-auto shrink-0 font-mono text-[0.6rem] tabular-nums text-ink-subtle"
                >
                  {relative(notification.createdAt, now, timezone)}
                </time>
              </span>
              <span
                className={cn(
                  "mt-1 block text-xs leading-snug",
                  isUnread ? "font-semibold text-ink" : "font-normal text-ink-muted",
                )}
              >
                {notification.title}
              </span>
              <span className="mt-0.5 block text-2xs leading-relaxed text-ink-muted">
                {notification.body}
              </span>
            </>
          );

          const content = (
            <li key={notification.id} className="relative pb-4 pl-5 last:pb-0">
              {/* The rule, stopping at the last entry so the timeline has a
                  definite end rather than trailing off. */}
              {!last ? (
                <span
                  aria-hidden
                  className="absolute bottom-0 left-[0.1875rem] top-3 w-px bg-rule"
                />
              ) : null}
              <span
                aria-hidden
                className={cn(
                  "absolute left-0 top-[0.3125rem] size-[0.375rem] rounded-pill ring-2 ring-surface",
                  isUnread ? "bg-ochre" : "bg-rule-strong",
                )}
              />
              {notification.href ? (
                <a
                  href={notification.href}
                  className="block rounded-sm underline-offset-2 hover:underline focus-visible:outline-2 focus-visible:outline-offset-2 focus-visible:outline-accent"
                >
                  {body}
                </a>
              ) : (
                body
              )}
            </li>
          );

          return content;
        })}
      </ol>
    </Panel>
  );
}

function relative(date: Date, now: Date, timezone: string): string {
  const minutes = Math.round((now.getTime() - date.getTime()) / 60_000);
  if (minutes < 1) return "just now";
  if (minutes < 60) return `${minutes}m ago`;
  const hours = Math.round(minutes / 60);
  if (hours < 24) return `${hours}h ago`;
  const days = Math.round(hours / 24);
  if (days < 7) return `${days}d ago`;
  return new Intl.DateTimeFormat("en-GB", { day: "numeric", month: "short", timeZone: timezone }).format(date);
}
